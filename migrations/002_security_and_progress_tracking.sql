--    نفس نمط الربط بعلاقة فعلية (محادثة مشتركة، أو معلم↔طالبه/وليّ أمره).
-- ---------------------------------------------------------------------------
drop policy if exists "quran_notifications insert any" on quran_notifications;
drop policy if exists "quran_notifications insert scoped" on quran_notifications;
create policy "quran_notifications insert scoped" on quran_notifications for insert to authenticated with check (
  is_admin() or my_role() = any(array['supervisor','executive']::user_role[])
  or user_id = auth.uid()
  or exists (
    select 1 from chats c where auth.uid() = any(c.party_ids) and quran_notifications.user_id = any(c.party_ids)
  )
  or exists (
    select 1 from students s
    where (s.login_id = quran_notifications.user_id or s.parent_id = quran_notifications.user_id)
      and (
        s.chosen_teacher_id = auth.uid()
        or exists (select 1 from groups g where g.id = s.group_id and g.teacher_id = auth.uid())
      )
  )
  or exists (
    select 1 from students s
    where (s.login_id = auth.uid() or s.parent_id = auth.uid())
      and (
        s.chosen_teacher_id = quran_notifications.user_id
        or exists (select 1 from groups g where g.id = s.group_id and g.teacher_id = quran_notifications.user_id)
      )
  )
);

