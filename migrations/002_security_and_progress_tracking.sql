-- ============================================================================
-- 002_security_and_progress_tracking.sql
--
-- Additive, non-destructive migration. Every statement is guarded
-- (`if not exists` / `create or replace` / `drop policy if exists`), so it is
-- safe to run once against the live project (yvloiecymqbhpoizfucl). Nothing
-- here deletes or mutates existing rows. Written against the live schema,
-- verified via the Supabase Management API before writing any statement.
--
-- Covers:
--  1. Soft-delete for students (deleted_at column) instead of hard DELETE.
--  2. admin_actions_log — audit trail for sensitive staff actions.
--  3. quran_ward_progress.marked_by_role — who actually marked a ward done
--     (student / parent / teacher), computed deterministically server-side.
--  4. Atomic RPCs for payment confirmation/rejection and subsidy rejection,
--     replacing multi-step client-side writes that had no error handling
--     between steps (a partial failure could leave payment/enrollment state
--     inconsistent with zero admin-facing error).
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1) Soft-delete for students
-- ---------------------------------------------------------------------------
alter table students add column if not exists deleted_at timestamptz;
alter table students add column if not exists deleted_by uuid references profiles(id);
alter table students add column if not exists delete_reason text;

-- ---------------------------------------------------------------------------
-- 2) Audit log for sensitive admin/staff actions
-- ---------------------------------------------------------------------------
create table if not exists admin_actions_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references profiles(id),
  actor_role text,
  action text not null,
  target_table text,
  target_id text,
  details jsonb,
  created_at timestamptz default now()
);
alter table admin_actions_log enable row level security;
drop policy if exists "admin_actions_log staff read" on admin_actions_log;
create policy "admin_actions_log staff read" on admin_actions_log for select to authenticated
  using (is_admin() or my_role() in ('executive','supervisor'));
-- عمدًا لا توجد سياسة INSERT/UPDATE/DELETE للعميل: الكتابة فقط عبر الدوال
-- SECURITY DEFINER أدناه، فلا يقدر أي مستخدم يزوّر أو يمسح سجل التدقيق.

create or replace function log_admin_action(p_action text, p_target_table text, p_target_id text, p_details jsonb default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into admin_actions_log(actor_id, actor_role, action, target_table, target_id, details)
  values (auth.uid(), (select role::text from profiles where id = auth.uid()), p_action, p_target_table, p_target_id, p_details);
end;
$$;

-- ---------------------------------------------------------------------------
-- 3) soft_delete_student — يستبدل الحذف النهائي بعلامة تاريخية + سجل تدقيق
-- ---------------------------------------------------------------------------
create or replace function soft_delete_student(p_student_id bigint, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_name text;
begin
  if not (is_admin() or my_role() in ('executive','supervisor')) then
    return jsonb_build_object('ok', false, 'error', 'forbidden');
  end if;
  select full_name into v_name from students where id = p_student_id;
  if v_name is null then
    return jsonb_build_object('ok', false, 'error', 'not_found');
  end if;
  update students set deleted_at = now(), deleted_by = auth.uid(), delete_reason = p_reason
  where id = p_student_id;
  perform log_admin_action('soft_delete_student', 'students', p_student_id::text, jsonb_build_object('full_name', v_name, 'reason', p_reason));
  return jsonb_build_object('ok', true);
end;
$$;

-- ---------------------------------------------------------------------------
-- 4) confirm_payment / reject_payment / reject_subsidy
--    نفس منطق العميل الحالي (confirmPay/rejectPay/rejectSubsidy في index.html)
--    حرفيًا، لكن كعملية واحدة ذرّية على السيرفر بدل خطوتين منفصلتين بلا تحقق
--    خطأ بينهما. الإشعارات لسه بتتبعت من العميل بعد نجاح الاستدعاء (نفس
--    pushNotif المُختبَر) — الدالة بترجع بيانات التواصل اللازمة لذلك فقط.
-- ---------------------------------------------------------------------------
create or replace function confirm_payment(p_payment_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student_id bigint;
  v_jr_id bigint;
  v_is_renewal boolean;
  v_sub_end timestamptz;
  v_base timestamptz;
  v_next_end timestamptz;
  v_full_name text;
  v_login_id uuid;
  v_parent_id uuid;
  v_updated int;
begin
  if not (is_admin() or my_role() in ('executive','supervisor')) then
    return jsonb_build_object('ok', false, 'error', 'forbidden');
  end if;

  select student_id, join_request_id into v_student_id, v_jr_id from payments where id = p_payment_id and status = 'pending';
  if v_student_id is null then
    return jsonb_build_object('ok', false, 'error', 'not_found_or_already_processed');
  end if;

  v_is_renewal := (v_jr_id is null);
  select sub_end, full_name, login_id, parent_id into v_sub_end, v_full_name, v_login_id, v_parent_id
  from students where id = v_student_id;

  v_base := now();
  if v_is_renewal and v_sub_end is not null and v_sub_end > v_base then
    v_base := v_sub_end;
  end if;
  v_next_end := v_base + interval '1 month';

  update payments set status = 'paid', paid_at = now(), confirmed_by = auth.uid()
  where id = p_payment_id and status = 'pending';
  get diagnostics v_updated = row_count;
  if v_updated = 0 then
    return jsonb_build_object('ok', false, 'error', 'race_condition_already_processed');
  end if;

  update students set
    enrollment_status = 'active',
    sub_start = case when v_is_renewal then coalesce(v_sub_end, now()) else now() end,
    sub_end = v_next_end,
    sub_anchored = v_is_renewal
  where id = v_student_id;

  perform log_admin_action('confirm_payment', 'payments', p_payment_id::text,
    jsonb_build_object('student_id', v_student_id, 'is_renewal', v_is_renewal, 'new_sub_end', v_next_end));

  return jsonb_build_object('ok', true, 'is_renewal', v_is_renewal, 'student_id', v_student_id,
    'full_name', v_full_name, 'login_id', v_login_id, 'parent_id', v_parent_id);
end;
$$;

create or replace function reject_payment(p_payment_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student_id bigint;
  v_full_name text;
  v_login_id uuid;
  v_parent_id uuid;
  v_updated int;
begin
  if not (is_admin() or my_role() in ('executive','supervisor')) then
    return jsonb_build_object('ok', false, 'error', 'forbidden');
  end if;

  update payments set status = 'rejected' where id = p_payment_id and status = 'pending';
  get diagnostics v_updated = row_count;
  if v_updated = 0 then
    return jsonb_build_object('ok', false, 'error', 'not_found_or_already_processed');
  end if;

  select student_id into v_student_id from payments where id = p_payment_id;
  select full_name, login_id, parent_id into v_full_name, v_login_id, v_parent_id from students where id = v_student_id;

  perform log_admin_action('reject_payment', 'payments', p_payment_id::text, jsonb_build_object('student_id', v_student_id));

  return jsonb_build_object('ok', true, 'student_id', v_student_id, 'full_name', v_full_name, 'login_id', v_login_id, 'parent_id', v_parent_id);
end;
$$;

create or replace function reject_subsidy(p_request_id bigint)
returns jsonb
